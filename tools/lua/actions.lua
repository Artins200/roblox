--[[
	CombatActions — библиотека процедурных анимаций боёвки.

	Каждое действие — это набор «ключей» (t = 0..1 прогресса) и событий
	(в нужный момент включаются вспышки/звук/трейл). Аниматор достаёт позу в
	текущий момент времени, смешивает с передвижением и накладывает на риг.

	Все углы задаются в ГРАДУСАХ через Pose.deg — так читать проще.

	Соглашение (см. Pose.lua):
	  p>0 — вперёд, y>0 — поворот корпуса «правое плечо вперёд», r>0 — вправо
	  plant() — компенсирует наклон корпуса, чтобы ноги оставались «в мире»
	           (иначе наклон торса утаскивает ноги за собой — это R6).
]]

local Pose = require(script.Parent:WaitForChild("CombatPose"))

local Actions = {}

-- ---------------------------------------------------------------------------
-- Помощники
-- ---------------------------------------------------------------------------

-- Компенсация наклона корпуса для «стоячих» поз: углы ног указываются
-- относительно земли, а не относительно торса.
local function plant(t)
	local body = t.body or {}
	local bp = body.p or 0
	local br = body.r or 0
	local ll = t.ll or {}
	local rl = t.rl or {}
	local out = {}
	for k, v in pairs(t) do
		out[k] = v
	end
	out.ll = { p = (ll.p or 0) - bp, y = ll.y, r = (ll.r or 0) - br }
	out.rl = { p = (rl.p or 0) - bp, y = rl.y, r = (rl.r or 0) - br }
	return out
end

local function keys(list)
	local out = {}
	for i = 1, #list do
		local entry = list[i]
		out[#out + 1] = { t = entry[1], pose = Pose.deg(plant(entry[2])) }
	end
	table.sort(out, function(a, b)
		return a.t < b.t
	end)
	return out
end

-- Ключи для воздушных/полётных поз (без компенсации — тело само рулит ногами)
local function airKeys(list)
	local out = {}
	for i = 1, #list do
		local entry = list[i]
		out[#out + 1] = { t = entry[1], pose = Pose.deg(entry[2]) }
	end
	table.sort(out, function(a, b)
		return a.t < b.t
	end)
	return out
end

