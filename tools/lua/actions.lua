-- ---------------------------------------------------------------------------
-- Регистрация действий
-- ---------------------------------------------------------------------------
local ACT = {}
Actions.ACT = ACT

local function act(name, dur, opts)
	opts = opts or {}
	opts.name = name
	opts.duration = dur
	if opts.loop == nil then
		opts.loop = false
	end
	if opts.chain == nil then
		opts.chain = dur * 0.55
	end
	if opts.weight == nil then
		opts.weight = 1
	end
	if opts.keys then
		-- air = поза целиком вращается вместе с корпусом (сальто, кувырки),
		-- не компенсируем наклон корпуса для ног
		local fn = opts.air and airKeys or keys
		opts.pose = fn(opts.keys)
		opts.keys = nil
	end
	if opts.airKeys then
		opts.pose = airKeys(opts.airKeys)
		opts.airKeys = nil
	end
	ACT[name] = opts
	return opts
end

